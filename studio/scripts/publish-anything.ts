/**
 * Puts every Anything project on GitHub, one repository each.
 *
 *   GH_TOKEN=… npm run publish:anything                 # dry run: says what it would do
 *   GH_TOKEN=… npm run publish:anything -- --yes        # creates the repos
 *   GH_TOKEN=… npm run publish:anything -- --yes --private
 *
 * Read this before running it, because the ask was "download the projects and
 * add them to GitHub" and the honest answer is smaller than that: the Anything
 * API exposes an inventory — project id, name, platform, published URL, and for
 * each module its name, type and path — and not the source of those modules.
 * There is no endpoint that hands back the files, and the API cannot be reached
 * from the usual build sandbox at all. So what is published here is everything
 * Anything will tell us about a project: its parts, what kind of thing each one
 * is, which shelf of this library it would go on, where the live app is, and a
 * README that says exactly that.
 *
 * The scan file is written by `npm run scan:anything` at build time, where the
 * key already is. Run this afterwards, from anywhere that can reach GitHub.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { categoriseApp, categoryOrder } from "../src/anythingCategories";
import { categoryInfo } from "../src/features";

interface ScannedApp {
  id: string;
  name: string;
  organizationName: string;
  platform: string;
  modules: string[];
  moduleCount: number;
  url?: string;
  updatedAt: string;
}

interface ScanFile {
  scannedAt: string;
  ok: boolean;
  reason?: string;
  apps: ScannedApp[];
  counts?: { projects: number; parts: number; unread: number };
}

/** A repository name that GitHub will accept, from a project name. */
export function repoName(name: string, id: string): string {
  const slug = name
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  return `anything-${slug || id.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}`;
}

/** The README for one project: what it is, what is in it, where it lives. */
export function readmeFor(app: ScannedApp, scannedAt: string): string {
  const reading = categoriseApp(app.modules);
  const byShelf = categoryOrder
    .map((category) => ({
      category,
      label: categoryInfo(category)?.label ?? category,
      parts: reading.parts.filter((part) => part.category === category && part.weight > 0),
    }))
    .filter((group) => group.parts.length > 0);

  return `# ${app.name}

${app.name} is an Anything app in the **${app.organizationName}** account, on ${app.platform}.
This repository is its inventory: every part Anything reports, grouped by what
kind of thing it is. It is generated, and regenerating it replaces it.

- **Project id:** \`${app.id}\`
- **Platform:** ${app.platform}
- **Parts:** ${app.moduleCount}
- **Last updated:** ${app.updatedAt || "not reported"}
- **Live at:** ${app.url ? `<${app.url}>` : "never published"}
- **Read by the Studio at:** ${scannedAt}

## What is in it

| Shelf | Parts |
| --- | --- |
${byShelf.map((group) => `| ${group.label} | ${group.parts.length} |`).join("\n") || "| — | 0 |"}
${reading.uncategorised ? `\n${reading.uncategorised} further part${reading.uncategorised === 1 ? "" : 's'} read as page copy — nothing in the name pointed anywhere else.\n` : ""}
${byShelf
  .map(
    (group) => `### ${group.label}

${group.parts.map((part) => `- ${part.name} — ${part.because}`).join("\n")}`
  )
  .join("\n\n")}

## What this is not

The Anything API exposes an inventory, not a repository: it will tell you a
module is called \`Booking form\` and that it lives at a path, and it will not
hand back the code inside it. So this repository contains no source from
${app.name}. It contains the list, the classification and the links, which is what
can be had without signing in and clicking Export.

If the source is needed in git, the route is: open the project in Anything, use
its own export or git integration, and push that to this repository — the name
is already taken, so it will land next to this README.

---

Generated by \`studio/scripts/publish-anything.ts\` from the build-time scan of
${scannedAt}.
`;
}

/** Talk to the GitHub REST API. Small enough not to need an SDK. */
const github = async (token: string, route: string, init: RequestInit = {}) => {
  const response = await fetch(`https://api.github.com${route}`, {
    ...init,
    headers: {
      Accept: "application/vnd.github+json",
      Authorization: `Bearer ${token}`,
      "X-GitHub-Api-Version": "2022-11-28",
      "Content-Type": "application/json",
      ...(init.headers ?? {}),
    },
  });
  const body = (await response.json().catch(() => null)) as Record<string, unknown> | null;
  return { ok: response.ok, status: response.status, body };
};

export const publish = async (options: { scanPath: string; localDir: string; token: string; yes: boolean; private: boolean }): Promise<number> => {
  if (!existsSync(options.scanPath)) {
    console.error(`No scan at ${options.scanPath}. Run \`npm run scan:anything\` first — it needs ANYTHING_API_KEY.`);
    return 1;
  }
  const scan = JSON.parse(readFileSync(options.scanPath, "utf8")) as ScanFile;
  if (!scan.ok) {
    console.error(`The last scan failed: ${scan.reason ?? "no reason recorded"}. Nothing to publish.`);
    return 1;
  }
  const TOKEN = options.token;
  const YES = options.yes;
  const PRIVATE = options.private;
  const LOCAL = options.localDir;
  const apps = scan.apps.filter((app) => app.id && app.name);
  console.log(`scan: ${apps.length} projects, ${apps.reduce((total, app) => total + app.moduleCount, 0)} parts, read ${scan.scannedAt}`);

  /* Always write the READMEs locally first: the repository has a record even if
     GitHub is unreachable, and the dry run has something to show. */
  mkdirSync(LOCAL, { recursive: true });
  for (const app of apps) {
    writeFileSync(path.join(LOCAL, `${app.id.replace(/[^a-z0-9_-]+/gi, "-")}.md`), readmeFor(app, scan.scannedAt), "utf8");
  }
  console.log(`wrote ${apps.length} README files → ${path.relative(process.cwd(), LOCAL)}`);

  if (!TOKEN) {
    console.log("No GH_TOKEN or GITHUB_TOKEN set: dry run only. Set one to create the repositories.");
    return 0;
  }
  if (!YES) {
    console.log("Dry run. Pass --yes to create the repositories. Would create:");
    for (const app of apps) console.log(`  ${repoName(app.name, app.id)} — ${app.moduleCount} parts${app.url ? ` — ${app.url}` : ""}`);
    return 0;
  }

  const who = await github(TOKEN, "/user");
  const owner = typeof who.body?.login === "string" ? who.body.login : "";
  if (!who.ok || !owner) {
    console.error(`GitHub would not say who the token is: ${who.status}. Nothing created.`);
    return 1;
  }
  console.log(`publishing as ${owner}${PRIVATE ? " (private)" : " (public)"}`);

  let created = 0;
  let updated = 0;
  let failed = 0;
  for (const app of apps) {
    const repo = repoName(app.name, app.id);
    const readme = readmeFor(app, scan.scannedAt);
    const existing = await github(TOKEN, `/repos/${owner}/${repo}`);
    if (!existing.ok && existing.status !== 404) {
      console.error(`  ${repo}: could not read the repo (${existing.status}). Skipped.`);
      failed += 1;
      continue;
    }
    if (existing.status === 404) {
      const made = await github(TOKEN, "/user/repos", {
        method: "POST",
        body: JSON.stringify({
          name: repo,
          private: PRIVATE,
          description: `${app.name} — the inventory of an Anything app: ${app.moduleCount} parts, grouped by shelf.`,
          has_issues: false,
          has_wiki: false,
          has_projects: false,
          auto_init: false,
        }),
      });
      if (!made.ok) {
        console.error(`  ${repo}: create failed (${made.status} ${String(made.body?.message ?? "")}).`);
        failed += 1;
        continue;
      }
      created += 1;
      console.log(`  ${repo}: created`);
    }
    /* The contents API needs the existing blob sha to update a file. */
    const current = await github(TOKEN, `/repos/${owner}/${repo}/contents/README.md`);
    const sha = typeof current.body?.sha === "string" ? current.body.sha : undefined;
    const put = await github(TOKEN, `/repos/${owner}/${repo}/contents/README.md`, {
      method: "PUT",
      body: JSON.stringify({
        message: `${app.name}: inventory from the Studio scan of ${scan.scannedAt.slice(0, 10)}`,
        content: Buffer.from(readme, "utf8").toString("base64"),
        ...(sha ? { sha } : {}),
      }),
    });
    if (!put.ok) {
      console.error(`  ${repo}: README write failed (${put.status}).`);
      failed += 1;
      continue;
    }
    updated += 1;
  }
  console.log(`done: ${created} created, ${updated} READMEs written, ${failed} failed`);
  return failed ? 1 : 0;
};

